# ========== 调用 DeepSeek 扩写 ==========
def generate_full_copy(seed):
    prompt = f"""你是一名资深小红书/抖音内容创作者，专精OLAY品牌。请根据以下真实种子，扩写成一条完整的营销文案。

【真实种子】
{seed}

【要求】
1. 如果是小红书：输出格式为“标题 | 正文 | 5个标签”，正文包含具体场景、真实体验、价格锚点、互动引导。
2. 如果是抖音：输出格式为“口播稿 | 行动指令”，口语化，前3秒有钩子，结尾有行动号召。
3. 严禁使用“最”“第一”“绝对”“100%”“根治”等禁用词。
4. 强调科学实证，可提及烟酰胺专利、胜肽成分等。
5. 避免限定性别，使用“宝子们”“朋友们”等中性称呼。
6. 直接输出文案，不要解释。

【输出格式示例】
小红书 | 标题：xxx | 正文：xxx | 标签：#xxx #xxx #xxx #xxx #xxx
抖音 | 口播稿：xxx | 行动指令：xxx
"""
    response = client.chat.completions.create(
        model="deepseek-chat",
        messages=[{"role": "user", "content": prompt}],
        temperature=0.9
    )
    return response.choices[0].message.content.strip()

